#!/usr/bin/env python3
"""Package assembler output into a MAME-loadable Neo Geo cartridge (adapted from neo-r-type).

MAME's neogeo/aes drivers load carts through a software list (-cart1 <name>), so this writes:
  <build>/<ngh>-*.{p1,s1,m1,v1,c1,c2}  padded ROM images (P1 word-swapped)
  <build>/chorensha.zip                the ROM set MAME looks up via -rompath
  <build>/hash/neogeo.xml              a one-entry software list (-hashpath <build>/hash)
Input: <build>/p1.bin, <build>/m1.bin; the C-ROM pair and the S-ROM from <gfx>/c1.bin, c2.bin,
s1.bin (tools/mkgfx.py, make gfx); the V-ROM from --vrom (build/snd/vrom.bin, tools/mksound.py: the
effects and tunes, 4 MB, one ymsnd:adpcma area that ADPCM-A and ADPCM-B both read).
The NGH number (the file prefix) is read from p1.bin's header (the word at $108, assembled from
NGH_NUMBER in src/shim/neogeo.inc): one source.
"""
import argparse
import hashlib
import os
import struct
import sys
import zipfile
import zlib

SOFTWARE = "chorensha"
NGH_AT = 0x108       # the cartridge header's NGH word

P1_SIZE = 0x100000   # 1 MB: the whole P1 window ($000000-$0FFFFF), no bank switching
S1_SIZE = 0x020000
M1_SIZE = 0x020000
M1_FIXED = 0x008000  # Z80 $0000-$7FFF: the only M-ROM window the driver uses
V1_SIZE = 0x400000   # the V-ROM: 4 MB (tools/mksound.py)
C_SIZE = 0x100000    # per chip


def pad(data, size, fill, label):
    if len(data) > size:
        sys.exit(f"error: {label} is {len(data):#x} bytes, exceeds {size:#x}")
    return bytes(data) + bytes([fill]) * (size - len(data))


def ngh(p1):
    """The NGH number in the cartridge header of P-ROM image `p1`."""
    return struct.unpack_from(">H", p1, NGH_AT)[0]


def word_swap(data):
    """68000 is big-endian; MAME's load16_word_swap expects swapped P-ROM files."""
    out = bytearray(data)
    out[0::2], out[1::2] = data[1::2], data[0::2]
    return bytes(out)


def read(path):
    with open(path, "rb") as f:
        return f.read()


def write_zip(path, files):
    """Zip {name: bytes} in dict order, every member dated 1980-01-01 00:00:00: the same files give
    the same zip bytes (mkstandin.py's set too)."""
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in files.items():
            z.writestr(zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0)), data,
                       compress_type=zipfile.ZIP_DEFLATED)


def rom_attrs(name, data):
    crc = zlib.crc32(data) & 0xFFFFFFFF
    sha1 = hashlib.sha1(data).hexdigest()
    return f'name="{name}" size="0x{len(data):06x}" crc="{crc:08x}" sha1="{sha1}"'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", default="build/neo")
    ap.add_argument("--gfx", default="build/gfx", help="tools/mkgfx.py's output: c1.bin, c2.bin, s1.bin")
    ap.add_argument("--vrom", default="build/snd/vrom.bin", help="tools/mksound.py's V-ROM")
    args = ap.parse_args(argv)
    b = args.build

    p1_raw = read(os.path.join(b, "p1.bin"))
    if p1_raw[0x100:0x107] != b"NEO-GEO":
        sys.exit("error: p1.bin has no NEO-GEO header at $100 (vector table must start at org 0)")
    prefix = "%03x" % ngh(p1_raw)
    m1_raw = read(os.path.join(b, "m1.bin"))
    if len(m1_raw) > M1_FIXED:
        sys.exit(f"error: m1.bin is {len(m1_raw):#x} bytes; it must fit in {M1_FIXED:#x}")

    roms = {
        f"{prefix}-p1.p1": word_swap(pad(p1_raw, P1_SIZE, 0xFF, "P-ROM")),
        f"{prefix}-s1.s1": pad(read(os.path.join(args.gfx, "s1.bin")), S1_SIZE, 0x00, "S-ROM"),
        f"{prefix}-m1.m1": pad(m1_raw, M1_SIZE, 0xFF, "M-ROM"),
        f"{prefix}-v1.v1": pad(read(args.vrom), V1_SIZE, 0x00, "V-ROM"),
        f"{prefix}-c1.c1": pad(read(os.path.join(args.gfx, "c1.bin")), C_SIZE, 0x00, "C1"),
        f"{prefix}-c2.c2": pad(read(os.path.join(args.gfx, "c2.bin")), C_SIZE, 0x00, "C2"),
    }

    for name, data in roms.items():
        with open(os.path.join(b, name), "wb") as f:
            f.write(data)

    write_zip(os.path.join(b, f"{SOFTWARE}.zip"), roms)

    r = {n.split(".")[1]: rom_attrs(n, d) for n, d in roms.items()}
    c_total = C_SIZE * 2
    xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE softwarelist SYSTEM "softwarelist.dtd">
<!-- generated by tools/mkcart.py - do not edit -->
<softwarelist name="neogeo" description="Neo-Chorensha development build">
\t<software name="{SOFTWARE}">
\t\t<description>Neo-Chorensha (development build)</description>
\t\t<year>2026</year>
\t\t<publisher>homebrew</publisher>
\t\t<sharedfeat name="release" value="MVS,AES" />
\t\t<sharedfeat name="compatibility" value="MVS,AES" />
\t\t<part name="cart" interface="neo_cart">
\t\t\t<dataarea name="maincpu" width="16" endianness="big" size="0x{P1_SIZE:06x}">
\t\t\t\t<rom loadflag="load16_word_swap" {r['p1']} offset="0x000000" />
\t\t\t</dataarea>
\t\t\t<dataarea name="fixed" size="0x{S1_SIZE:06x}">
\t\t\t\t<rom {r['s1']} offset="0x000000" />
\t\t\t</dataarea>
\t\t\t<dataarea name="audiocpu" size="0x{M1_SIZE:06x}">
\t\t\t\t<rom {r['m1']} offset="0x000000" />
\t\t\t</dataarea>
\t\t\t<dataarea name="ymsnd:adpcma" size="0x{V1_SIZE:06x}">
\t\t\t\t<rom {r['v1']} offset="0x000000" />
\t\t\t</dataarea>
\t\t\t<dataarea name="sprites" size="0x{c_total:06x}">
\t\t\t\t<rom loadflag="load16_byte" {r['c1']} offset="0x000000" />
\t\t\t\t<rom loadflag="load16_byte" {r['c2']} offset="0x000001" />
\t\t\t</dataarea>
\t\t</part>
\t</software>
</softwarelist>
"""
    os.makedirs(os.path.join(b, "hash"), exist_ok=True)
    with open(os.path.join(b, "hash", "neogeo.xml"), "w") as f:
        f.write(xml)
    print(f"Packaged {b}/{SOFTWARE}.zip and {b}/hash/neogeo.xml")


if __name__ == "__main__":
    main()
